/*
 * Assembles the files Rails serves (app/assets/builds) from the vendored
 * EasyMDE distribution and this gem's own sources.
 *
 * The gem ships prebuilt assets because Administrate 1.0 dropped its
 * sprockets-rails dependency: a `//= require` directive would only resolve for
 * hosts still running Sprockets, while a plain concatenated file resolves under
 * Sprockets and Propshaft alike.
 *
 * Run with `rake assets:build`.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (path) => readFileSync(resolve(root, path), "utf8");

const easymdeVersion = read("vendor/easymde/VERSION").trim();
const dompurifyVersion = read("vendor/dompurify/VERSION").trim();

/*
 * EasyMDE renders its toolbar with Font Awesome classes and, by default,
 * injects a <link> to a Font Awesome CDN at runtime. That is a third-party
 * request from every admin form page and it breaks under a strict
 * Content-Security-Policy, so the field turns the download off and draws the
 * toolbar with these icons instead. Keys are EasyMDE toolbar button names.
 */
const ICONS = {
  bold: "type-bold",
  italic: "type-italic",
  strikethrough: "type-strikethrough",
  heading: "type-h1",
  "heading-smaller": "type-h2",
  "heading-bigger": "type-h1",
  "heading-1": "type-h1",
  "heading-2": "type-h2",
  "heading-3": "type-h3",
  "heading-4": "type-h4",
  "heading-5": "type-h5",
  "heading-6": "type-h6",
  code: "code-slash",
  quote: "quote",
  "ordered-list": "list-ol",
  "unordered-list": "list-ul",
  "check-list": "check2-square",
  "clean-block": "eraser",
  link: "link-45deg",
  image: "image",
  "upload-image": "file-earmark-image",
  table: "table",
  "horizontal-rule": "dash-lg",
  preview: "eye",
  "side-by-side": "layout-split",
  fullscreen: "arrows-fullscreen",
  guide: "question-circle",
  undo: "arrow-counterclockwise",
  redo: "arrow-clockwise"
};

// Must match Administrate::Field::SimpleMarkdown::TOOLBAR_BUTTON_CLASS_PREFIX.
const PREFIX = "administrate-easymde";

function dataUri(iconName) {
  const svg = read(`node_modules/bootstrap-icons/icons/${iconName}.svg`)
    .replace(/\s*\n\s*/g, " ")
    .trim();

  return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
}

function iconCss() {
  const rules = Object.entries(ICONS).map(([button, icon]) => {
    return `.editor-toolbar button.${PREFIX}-${button} > i {\n  mask-image: ${dataUri(icon)};\n  -webkit-mask-image: ${dataUri(icon)};\n}`;
  });

  return [
    "/* Bundled toolbar icons: Bootstrap Icons v" +
      JSON.parse(read("node_modules/bootstrap-icons/package.json")).version +
      " (MIT). See NOTICE.md. */",
    `.editor-toolbar button[class^="${PREFIX}-"] > i,`,
    `.editor-toolbar button[class*=" ${PREFIX}-"] > i {`,
    "  display: inline-block;",
    "  width: 1em;",
    "  height: 1em;",
    "  vertical-align: -0.125em;",
    "  background-color: currentColor;",
    "  mask-repeat: no-repeat;",
    "  mask-position: center;",
    "  mask-size: contain;",
    "  -webkit-mask-repeat: no-repeat;",
    "  -webkit-mask-position: center;",
    "  -webkit-mask-size: contain;",
    "}",
    "",
    rules.join("\n\n")
  ].join("\n");
}

function banner(kind) {
  return [
    "/*!",
    " * administrate-field-easymde bundled " + kind,
    " * Generated by `rake assets:build` - edit the sources, not this file.",
    " * Bundles EasyMDE v" + easymdeVersion + " (MIT) by Jeroen Akkerman",
    " * and DOMPurify v" + dompurifyVersion + " (Apache-2.0 OR MPL-2.0) by Cure53.",
    " */",
    ""
  ].join("\n");
}

function write(path, contents) {
  const target = resolve(root, path);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, contents);
  console.log(`wrote ${path} (${(contents.length / 1024).toFixed(1)} KB)`);
}

write(
  "app/assets/builds/administrate-field-easymde/application.js",
  [
    banner("JavaScript"),
    read("vendor/dompurify/purify.min.js"),
    "\n",
    read("vendor/easymde/easymde.min.js"),
    "\n",
    read("app/assets/javascripts/administrate-field-easymde/easymde_field.js")
  ].join("\n")
);

write(
  "app/assets/builds/administrate-field-easymde/application.css",
  [
    banner("stylesheet"),
    read("vendor/easymde/easymde.min.css"),
    "\n",
    iconCss(),
    "\n",
    read("app/assets/stylesheets/administrate-field-easymde/easymde_field.css")
  ].join("\n")
);
